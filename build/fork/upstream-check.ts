// Verifies that every upstream file VS NOSH modifies is listed in build/fork/upstream-patches.json,
// that no stale entries remain, that the fork gate is never spelled as a raw string, that the gate
// import is the last import of each patched file, and that docs/upstream/PATCHES.md is current.
//
//   node build/fork/upstream-check.ts [--markdown] [--diffstat]

import { execFileSync } from 'child_process';
import { existsSync, readFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

interface IPatch {
	readonly path: string;
	readonly kind: 'hook-callout' | 'gate' | 'additive-api' | 'branding' | 'build' | 'generic-fix' | 'test';
	readonly gated: boolean;
	readonly seam: string;
	readonly why: string;
	readonly validate: readonly string[];
}

interface IManifest {
	readonly base: string;
	readonly forkPaths: readonly string[];
	readonly forkOwnedInUpstreamDirs: readonly string[];
	readonly patches: readonly IPatch[];
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const manifestPath = join(root, 'build', 'fork', 'upstream-patches.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as IManifest;
const base = readFileSync(join(root, manifest.base), 'utf8').trim();
const gateModule = 'src/vs/platform/terminalFirst/common/terminalFirstProduct.ts';
const docPath = 'docs/upstream/PATCHES.md';

function git(...args: string[]): string {
	return execFileSync('git', args, { cwd: root, encoding: 'utf8' });
}

function isForkPath(path: string): boolean {
	return manifest.forkPaths.some(prefix => prefix.endsWith('/') ? path.startsWith(prefix) : path === prefix);
}

function markdown(): string {
	const lines = [
		'# Upstream patches',
		'',
		`Generated by \`scripts/upstream-check.sh --markdown\` from \`build/fork/upstream-patches.json\`. Base: \`${base}\`. Do not edit by hand.`,
		'',
		'Every upstream file VS NOSH modifies, the seam it uses, and how to re-validate it after a merge. See [SYNC.md](SYNC.md) for the merge procedure.',
		'',
		'| Path | Kind | Gated | Seam | Why | Validate |',
		'| --- | --- | --- | --- | --- | --- |',
	];
	for (const patch of [...manifest.patches].sort((a, b) => a.path.localeCompare(b.path))) {
		lines.push(`| \`${patch.path}\` | ${patch.kind} | ${patch.gated ? 'yes' : 'no'} | ${patch.seam} | ${patch.why} | ${patch.validate.map(v => `\`${v}\``).join(', ')} |`);
	}
	lines.push('', '## Fork-owned files in upstream directories', '', 'New files that never conflict but live next to upstream code:', '');
	for (const path of manifest.forkOwnedInUpstreamDirs) {
		lines.push(`- \`${path}\``);
	}
	lines.push('');
	return lines.join('\n');
}

const args = new Set(process.argv.slice(2));
if (args.has('--markdown')) {
	process.stdout.write(markdown());
	process.exit(0);
}

const problems: string[] = [];
const warnings: string[] = [];

// 1. Every modified upstream file is documented, and every entry still differs.
const touched = git('diff', '--name-only', base, '--').split('\n').map(line => line.trim()).filter(Boolean);
const upstreamTouched = touched.filter(path => !isForkPath(path));
const documented = new Set([...manifest.patches.map(patch => patch.path), ...manifest.forkOwnedInUpstreamDirs]);
for (const path of upstreamTouched) {
	if (!documented.has(path)) {
		problems.push(`Undocumented upstream edit: ${path} (add it to build/fork/upstream-patches.json or move the change into a fork path)`);
	}
}
const touchedSet = new Set(touched);
for (const patch of manifest.patches) {
	if (!touchedSet.has(patch.path)) {
		warnings.push(`Stale manifest entry: ${patch.path} no longer differs from the base`);
	}
}
for (const path of manifest.forkOwnedInUpstreamDirs) {
	if (!existsSync(join(root, path))) {
		warnings.push(`Fork-owned file listed in the manifest is missing: ${path}`);
	}
}

// 2. The gate is spelled once.
const rawGate = git('grep', '-n', '=== \'terminal-first\'', '--', 'src/vs/*.ts').split('\n').filter(line => line && !line.startsWith(gateModule + ':') && !line.startsWith('src/vs/code/electron-browser/workbench/workbench.ts:') && !line.includes('/test/'));
for (const hit of rawGate) {
	problems.push(`Raw 'terminal-first' check outside ${gateModule}: ${hit}`);
}

// 3. The gate import is the last import of each patched file.
for (const patch of manifest.patches) {
	if (!patch.path.endsWith('.ts')) {
		continue;
	}
	const file = join(root, patch.path);
	if (!existsSync(file)) {
		continue;
	}
	const lines = readFileSync(file, 'utf8').split('\n');
	const imports = lines.map((line, index) => ({ line, index })).filter(({ line }) => line.startsWith('import '));
	const gate = imports.find(({ line }) => /terminalFirst\/common\/terminalFirst(?:Policy|Product)?\.js['"]/.test(line));
	if (gate && imports[imports.length - 1].index !== gate.index) {
		problems.push(`${patch.path}: the terminalFirst import must be the last import (line ${gate.index + 1})`);
	}
}

// 4. The generated table is current.
const expected = markdown();
const actual = existsSync(join(root, docPath)) ? readFileSync(join(root, docPath), 'utf8') : '';
if (expected !== actual) {
	problems.push(`${docPath} is out of date; run: scripts/upstream-check.sh --markdown > ${docPath}`);
}

if (args.has('--diffstat')) {
	process.stdout.write(git('diff', '--stat', base, '--', ...manifest.patches.map(patch => patch.path)));
}

for (const warning of warnings) {
	console.warn(`warning: ${warning}`);
}
for (const problem of problems) {
	console.error(`error: ${problem}`);
}
console.log(`upstream-check: ${manifest.patches.length} documented patches, ${upstreamTouched.length} modified upstream files, ${problems.length} problem(s), ${warnings.length} warning(s)`);
process.exit(problems.length ? 1 : 0);
